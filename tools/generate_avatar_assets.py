#!/usr/bin/env python3
"""Generate original JEDL Studio humanoid PNG pieces for Android assets."""
from pathlib import Path
import json
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app/src/main/assets/pieces/ritmo"
OUT.mkdir(parents=True, exist_ok=True)

# Local bone coordinates: the pivot is near the top edge; positive Y follows the bone.
SPECS = [
    ("armUR", "armUR.png", "skin", (256, 640), 0.055, "upper"),
    ("foreArmR", "foreArmR.png", "skin", (256, 640), 0.050, "lower"),
    ("thighR", "thighR.png", "pants", (300, 640), 0.070, "upper"),
    ("shinR", "shinR.png", "pants", (280, 640), 0.058, "lower"),
    ("torso", "torso.png", "shirt", (512, 640), 0.220, "torso"),
    ("thighL", "thighL.png", "pants", (300, 640), 0.070, "upper"),
    ("shinL", "shinL.png", "pants", (280, 640), 0.058, "lower"),
    ("head", "head.png", "skin", (512, 512), 0.170, "head"),
    ("armUL", "armUL.png", "skin", (256, 640), 0.055, "upper"),
    ("foreArmL", "foreArmL.png", "skin", (256, 640), 0.050, "lower"),
]

def draw_piece(filename, size, kind, mirror=False):
    scale = 3
    w, h = size
    im = Image.new("RGBA", (w*scale, h*scale), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    def xy(box): return tuple(int(v*scale) for v in box)
    outline = (45, 39, 35, 255)
    fill = (255, 255, 255, 255)
    detail = (110, 110, 110, 230)
    if kind in ("upper", "lower"):
        cx = w/2
        top, bottom = 20, h-18
        half = 76 if kind == "upper" else 68
        d.rounded_rectangle(xy((cx-half, top, cx+half, bottom)), radius=int(half*0.78*scale), fill=fill, outline=outline, width=5*scale)
        d.ellipse(xy((cx-38, top-9, cx+38, top+67)), fill=fill, outline=outline, width=4*scale)
        d.arc(xy((cx-half+8, h*0.43, cx+half-8, h*0.57)), 0, 180, fill=detail, width=3*scale)
        if kind == "lower":
            d.rounded_rectangle(xy((cx-78, bottom-75, cx+78, bottom+2)), radius=24*scale, fill=fill, outline=outline, width=4*scale)
    elif kind == "torso":
        d.rounded_rectangle(xy((80, 18, w-80, h-12)), radius=88*scale, fill=fill, outline=outline, width=6*scale)
        d.line(xy((w/2, 65, w/2, h-35)), fill=detail, width=4*scale)
        d.arc(xy((95, 35, w-95, 220)), 0, 180, fill=detail, width=4*scale)
        d.ellipse(xy((w/2-14, 105, w/2+14, 133)), fill=detail)
        d.ellipse(xy((w/2-14, 190, w/2+14, 218)), fill=detail)
    elif kind == "head":
        d.ellipse(xy((40, 28, w-40, h-28)), fill=fill, outline=outline, width=7*scale)
        d.arc(xy((78, 95, w-78, h-55)), 200, 340, fill=detail, width=5*scale)
        d.ellipse(xy((155, 230, 180, 255)), fill=outline)
        d.ellipse(xy((w-180, 230, w-155, 255)), fill=outline)
        d.arc(xy((165, 260, w-165, 365)), 15, 165, fill=detail, width=5*scale)
    if mirror:
        im = im.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
    im.resize((w, h), Image.Resampling.LANCZOS).save(OUT / filename, format="PNG", optimize=True)

pieces = []
for bone, filename, tint, size, width_units, kind in SPECS:
    draw_piece(filename, size, kind, mirror=bone.endswith("L"))
    pieces.append({
        "bone": bone, "file": filename,
        "pivotX": size[0] / 2, "pivotY": 20 if kind != "head" else 28,
        "widthUnits": width_units, "tint": tint
    })

manifest = {
    "view": "frente",
    "faceRect": {"x": 0.28, "y": 0.24, "w": 0.44, "h": 0.46},
    "pieces": pieces
}
(OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
(OUT / "LICENSE.md").write_text(
    "# JEDL Studio — Avatar PNG assets\n\n"
    "These ten PNG files are original project artwork generated by "
    "tools/generate_avatar_assets.py for JEDL Studio. They are not copied "
    "from third-party packs or stock libraries. Copyright (c) 2026 JEDL Studio project. "
    "All rights reserved. The generator source is part of this repository.\n",
    encoding="utf-8"
)

expected = {s[0] for s in SPECS}
assert len(pieces) == 10 and {p["bone"] for p in pieces} == expected
for p in pieces:
    with Image.open(OUT / p["file"]) as im:
        im.verify()
assert json.loads((OUT / "manifest.json").read_text())["pieces"] == pieces
print(f"Generated and verified {len(pieces)} original avatar PNG pieces in {OUT}")
